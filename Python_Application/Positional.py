def AreaOfCircle(Radius,PI):
    Ans = PI* Radius *Radius
    return Ans
    
def main():
    Ret1 = AreaOfCircle(10.5,3.14)
    print("Area of Circle is:",Ret1)
    
    Ret2 = AreaOfCircle(13.6,7.12)
    print("Area of Circle is:",Ret2)

if __name__ == "__main__":
    main()
    
    
    
    
    
    